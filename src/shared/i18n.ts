export type MsgKey = keyof typeof DICT

/** Values substituted into the `{name}` placeholders of a message. */
export type MsgParams = Readonly<Record<string, string | number>>

/** Looks `key` up for `locale` and fills its placeholders. */
export function t(locale: Locale, key: MsgKey, params?: MsgParams): string {
  const entry = DICT[key] as Entry | undefined
  if (!entry) return key
  const template = locale === 'en' ? entry.en : entry['zh-Hans']
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (placeholder: string, name: string) => {
    const value = params[name]
    return value === undefined ? placeholder : String(value)
  })
}

/**
 * `system` follows the OS: the first navigator language we ship wins, and any
 * other language falls back to English.
 */
export function resolveLocale(setting: UiLanguage, navigatorLanguages: readonly string[]): Locale {
  if (setting !== 'system') return setting
  for (const tag of navigatorLanguages) {
    const primary = tag.toLowerCase().split(/[-_]/)[0]
    if (primary === 'zh') return 'zh-Hans'
    if (primary === 'en') return 'en'
  }
  return 'en'
}
