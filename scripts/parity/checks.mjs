/**
 * Typora parity checks -- the difference list this harness walks.
 *
 * One entry is:
 *
 *   { id, area, description, probe, initial?, settings? }
 *
 *   id           stable handle, <area>.<name>
 *   area         attribution bucket: input | render | ui | settings | storage | tabs |
 *                save | find | table | list | format | theme | view | status | export |
 *                prefs | style
 *   description  the Typora behaviour being compared against, in one line
 *   probe        body of an async function evaluated inside the renderer page after a
 *                fresh Page.reload. It must return { expect, actual }; the runner decides
 *                PASS by comparing the two by value and prints both on FAIL. Probes never
 *                write the DOM: every input goes through H.* which the driver turns into
 *                CDP Input.dispatchKeyEvent / dispatchMouseEvent, i.e. the same events a
 *                keyboard or a mouse produces.
 *   initial      Markdown the document is loaded with before the reload (default '')
 *   settings     settings patch applied through the app's own IPC before the reload
 *
 * Page helpers (installed by run.mjs before the app boots):
 *   read    H.write() H.q(sel) H.qa(sel) H.tags(sel) H.blocks() H.text(sel) H.html(sel?)
 *           H.plain() H.attr(sel,name) H.exists(sel) H.count(sel) H.selectedText()
 *   input   H.type(text) H.key(name[,mods]) H.chord(mod,letter) H.click(sel)
 *           H.dclickText(word) H.selectChars(from,count) H.focus() H.focusBlock(n)
 *   driver  H.md() H.file() H.readText(path) H.fileStat(path) H.scratch(name)
 *           H.menu() H.menuCount() H.menuClick(id) H.menuChecked(id)
 *           H.stubDialogs(opts) H.dialogLog() H.exportFile(kind) H.converter()
 *           H.conf() H.prefsClick(label[,panel]) H.prefsRows() H.prefsReset() H.cssScan()
 */

